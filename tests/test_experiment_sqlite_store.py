def _corrupt_event(connection: sqlite3.Connection, corruption: str) -> None:
    if corruption == "json":
        event_json = "{"
        connection.execute(
            """
            UPDATE events SET event_json = ?, event_hash = ?
            WHERE attempt_id = ? AND sequence_no = 1
            """,
            (event_json, sha256(event_json.encode("utf-8")).hexdigest(), "attempt-1"),
        )
    elif corruption == "hash":
        connection.execute(
            "UPDATE events SET event_hash = ? WHERE attempt_id = ? AND sequence_no = 1",
            ("0" * 64, "attempt-1"),
        )
    elif corruption == "sequence":
        connection.execute(
            "UPDATE events SET sequence_no = 9 WHERE attempt_id = ? AND sequence_no = 1",
            ("attempt-1",),
        )
    elif corruption == "identity":
        connection.execute(
            "UPDATE events SET event_id = ? WHERE attempt_id = ? AND sequence_no = 1",
            (str(UUID(int=9999)), "attempt-1"),
        )
    elif corruption == "chain":
        connection.execute(
            """
            UPDATE events SET previous_event_hash = ?
            WHERE attempt_id = ? AND sequence_no = 2
            """,
            ("f" * 64, "attempt-1"),
        )
    elif corruption == "noncanonical":
        row = connection.execute(
            """
            SELECT event_json FROM events
            WHERE attempt_id = ? AND sequence_no = 1
            """,
            ("attempt-1",),
        ).fetchone()
        event_json = json.dumps(json.loads(row[0]), indent=2, sort_keys=True)
        event_hash = sha256(event_json.encode("utf-8")).hexdigest()
        connection.execute(
            """
            UPDATE events SET event_json = ?, event_hash = ?
            WHERE attempt_id = ? AND sequence_no = 1
            """,
            (event_json, event_hash, "attempt-1"),
        )
        connection.execute(
            """
            UPDATE events SET previous_event_hash = ?
            WHERE attempt_id = ? AND sequence_no = 2
            """,
            (event_hash, "attempt-1"),
        )
    else:
        raise AssertionError(f"unknown test corruption: {corruption}")


