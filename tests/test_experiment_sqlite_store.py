def _convert_to_genuine_v1_fixture(database_path: Path) -> None:
    with _connect(database_path) as connection:
        connection.execute("DROP INDEX action_outbox_claim_order")
        connection.execute("ALTER TABLE action_outbox RENAME TO action_outbox_newer")
        connection.execute(_V1_ACTION_OUTBOX_DDL)
        connection.execute(
            """
            INSERT INTO action_outbox(
                attempt_id, action_id, action_json, action_status,
                recovery_policy, idempotency_key, accepted_sequence_no,
                delivery_state, lease_owner, lease_expires_at
            )
            SELECT attempt_id, action_id, action_json, action_status,
                   recovery_policy, idempotency_key, accepted_sequence_no,
                   delivery_state, lease_owner, lease_expires_at
            FROM action_outbox_newer
            """
        )
        connection.execute("DROP TABLE action_outbox_newer")
        connection.execute(
            """
            CREATE INDEX action_outbox_claim_order
            ON action_outbox(accepted_sequence_no, action_id, attempt_id)
            """
        )
        rows = tuple(
            connection.execute(
                """
                SELECT sequence_no, event_json FROM events
                WHERE attempt_id = ? ORDER BY sequence_no
                """,
                (_create_command().attempt_id,),
            )
        )
        previous_hash = None
        for sequence_no, raw_json in rows:
            payload = json.loads(raw_json)
            if payload["event_type"] == "STRATEGY_DECISION_RECORDED":
                for field in (
                    "trigger_sequence_no",
                    "proposals",
                    "directive",
                    "result_ref",
                    "error",
                ):
                    payload.pop(field, None)
                raw_json = json.dumps(
                    payload,
                    ensure_ascii=False,
                    allow_nan=False,
                    sort_keys=True,
                    separators=(",", ":"),
                )
            event_hash = sha256(raw_json.encode("utf-8")).hexdigest()
            connection.execute(
                """
                UPDATE events
                SET event_json = ?, event_hash = ?, previous_event_hash = ?
                WHERE attempt_id = ? AND sequence_no = ?
                """,
                (
                    raw_json,
                    event_hash,
                    previous_hash,
                    _create_command().attempt_id,
                    sequence_no,
                ),
            )
            previous_hash = event_hash
        connection.execute(
            """
            UPDATE attempt_heads SET latest_event_hash = ? WHERE attempt_id = ?
            """,
            (previous_hash, _create_command().attempt_id),
        )
        connection.execute("UPDATE schema_meta SET version = 1")


