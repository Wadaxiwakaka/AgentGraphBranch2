@pytest.mark.asyncio
async def test_every_connection_is_opened_and_closed_in_a_worker_thread(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    event_loop_thread_id = threading.get_ident()
    open_threads: dict[int, int] = {}
    close_threads: dict[int, int] = {}
    traced_statements: list[tuple[int, int, str]] = []
    connection_counter = 0
    real_connect = sqlite_module.sqlite3.connect

    class TrackingConnection:
        def __init__(self, connection: sqlite3.Connection, token: int) -> None:
            object.__setattr__(self, "_connection", connection)
            object.__setattr__(self, "_token", token)
            connection.set_trace_callback(
                lambda statement: traced_statements.append(
                    (token, threading.get_ident(), statement)
                )
            )

        def __getattr__(self, name: str) -> object:
            return getattr(self._connection, name)

        def __setattr__(self, name: str, value: object) -> None:
            setattr(self._connection, name, value)

        def close(self) -> None:
            close_threads[self._token] = threading.get_ident()
            self._connection.close()

    def tracking_connect(*args: object, **kwargs: object) -> TrackingConnection:
        nonlocal connection_counter
        connection_counter += 1
        token = connection_counter
        open_threads[token] = threading.get_ident()
        return TrackingConnection(real_connect(*args, **kwargs), token)

    monkeypatch.setattr(sqlite_module.sqlite3, "connect", tracking_connect)
    repository = SQLiteAttemptRepository(tmp_path / "threading.sqlite3")

    assert await repository.load("missing") is None
    rejection = _rejected_request(seed=7100)
    await repository.record_rejection(rejection)
    assert await repository.find_command("missing", rejection.command_id) is not None
    await repository.commit(_create_request())
    assert len(await repository.list_events("attempt-1")) == 1
    assert await repository.claim_action(
        worker_id="worker-a",
        now_utc=UTC_NOW,
        lease_seconds=10,
    ) is None
    assert await repository.list_nonterminal_attempt_ids() == ("attempt-1",)

    assert open_threads
    assert open_threads.keys() == close_threads.keys()
    assert all(thread_id != event_loop_thread_id for thread_id in open_threads.values())
    assert close_threads == open_threads
    assert all(
        trace_thread_id == open_threads[token]
        for token, trace_thread_id, _ in traced_statements
    )
    statements_by_connection = {
        token: {
            "".join(statement.upper().split())
            for traced_token, _, statement in traced_statements
            if traced_token == token
        }
        for token in open_threads
    }
    for statements in statements_by_connection.values():
        assert "PRAGMAJOURNAL_MODE=WAL" in statements
        assert "PRAGMAFOREIGN_KEYS=ON" in statements
        assert "PRAGMABUSY_TIMEOUT=5000" in statements
    begin_statements = [
        statement.strip().upper()
        for _, _, statement in traced_statements
        if statement.strip().upper().startswith("BEGIN")
    ]
    assert len(begin_statements) >= 3
    assert set(begin_statements) == {"BEGIN IMMEDIATE"}


