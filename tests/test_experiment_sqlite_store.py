@contextmanager
def _connect(database_path: Path) -> Iterator[sqlite3.Connection]:
    connection = sqlite3.connect(database_path)
    connection.execute("PRAGMA foreign_keys=ON")
    try:
        yield connection
    except BaseException:
        connection.rollback()
        raise
    else:
        connection.commit()
    finally:
        connection.close()


def _fetchall(
    database_path: Path,
    sql: str,
    parameters: tuple[object, ...] = (),
) -> tuple[tuple[object, ...], ...]:
    with _connect(database_path) as connection:
        return tuple(connection.execute(sql, parameters).fetchall())


def _table_snapshot(database_path: Path) -> dict[str, tuple[tuple[object, ...], ...]]:
    tables = (
        "events",
        "attempt_heads",
        "attempt_checkpoints",
        "commands",
        "artifacts",
        "attempt_artifacts",
        "action_outbox",
    )
    return {
        table: _fetchall(database_path, f"SELECT * FROM {table} ORDER BY rowid")
        for table in tables
    }


def _database_dump(database_path: Path) -> tuple[str, ...]:
    with sqlite3.connect(database_path) as connection:
        return tuple(connection.iterdump())


def _artifact_key(ref: ArtifactRef) -> str:
    payload = json.dumps(
        ref.model_dump(mode="json"),
        ensure_ascii=False,
        allow_nan=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return sha256(payload).hexdigest()


